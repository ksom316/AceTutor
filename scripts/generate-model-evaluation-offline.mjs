/**
 * Phase A8 — regenerate src/lib/model-evaluation.offline.generated.ts from
 * COMMITTED metadata only, so a fresh clone produces the identical evaluation
 * page with no gitignored model artifact present.
 *
 *   node scripts/generate-model-evaluation-offline.mjs
 *
 * Sources of truth (both committed, small, no .joblib):
 *   - ml/vark/service/model/model_metadata.json      — the AUTHORITATIVE
 *     deployed 4-feature GradientBoosting model.
 *   - ml/vark/experiments/behavioral-8feature-experiment.json — the historical
 *     8-feature "behavioral" experiment (synthetic, experimental_not_deployable,
 *     NOT the deployed model). Metrics transcribed verbatim from the training
 *     run; never regenerated here.
 *
 * This script never trains or evaluates anything. src/lib/
 * model-evaluation.test.ts asserts the generated file still matches both.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const DEPLOYED_META = join(repoRoot, "ml/vark/service/model/model_metadata.json");
const EXPERIMENT_8F = join(repoRoot, "ml/vark/experiments/behavioral-8feature-experiment.json");
const OUT = join(repoRoot, "src/lib/model-evaluation.offline.generated.ts");

const meta = JSON.parse(readFileSync(DEPLOYED_META, "utf8"));
const exp8 = JSON.parse(readFileSync(EXPERIMENT_8F, "utf8"));

const modelMetrics = (m) => ({
  accuracy: m.accuracy,
  macroPrecision: m.macro_precision,
  macroRecall: m.macro_recall,
  macroF1: m.macro_f1,
  cvAccuracyMean: m.cross_validation.accuracy_mean,
  cvAccuracyStd: m.cross_validation.accuracy_std,
  cvMacroF1Mean: m.cross_validation.macro_f1_mean,
  cvMacroF1Std: m.cross_validation.macro_f1_std,
});

const priorExperiment = {
  modelVersion: exp8.modelVersion,
  winner: exp8.winner,
  deploymentStatus: exp8.deploymentStatus,
  featureSet: exp8.featureSet,
  featureNames: exp8.featureNames,
  datasetType: exp8.datasetType,
  isDeployedModel: false,
  randomForest: exp8.models.randomForest,
  gradientBoosting: exp8.models.gradientBoosting,
  note:
    "Synthetic, experimental_not_deployable — the behavioral 8-feature experiment, " +
    "NOT the deployed model. Adds four SIMULATED engagement signals AceTutor does not " +
    "collect; higher synthetic scores are not comparable to real-world accuracy.",
};

const summary = {
  generatedFrom: "ml/vark/service/model/model_metadata.json",
  modelVersion: meta.model_version,
  schemaVersion: meta.schema_version,
  deployedModelType: meta.model_type,
  winner: meta.winner,
  featureSet: meta.feature_set,
  featureNames: meta.feature_names,
  classLabels: meta.class_labels,
  trainingDataSource: meta.dataset_type,
  deploymentStatus: meta.deployment_status,
  datasetSize: meta.dataset_size,
  trainSize: meta.train_size,
  testSize: meta.test_size,
  selectionMetric: meta.selection_metric,
  selectionSecondaryMetric: meta.selection_secondary_metric,
  reportedMetricsComputedOn: meta.reported_metrics_computed_on,
  trainingTimestamp: meta.training_timestamp,
  models: {
    randomForest: modelMetrics(meta.models_compared.random_forest),
    gradientBoosting: modelMetrics(meta.models_compared.gradient_boosting),
  },
  syntheticDisclaimer: meta.limitations[0],
  limitations: meta.limitations,
  priorExperiment8Feature: priorExperiment,
};

const banner =
  "// AUTO-GENERATED by scripts/generate-model-evaluation-offline.mjs — DO NOT EDIT.\n" +
  "// Sources of truth (committed): ml/vark/service/model/model_metadata.json +\n" +
  "// ml/vark/experiments/behavioral-8feature-experiment.json.\n" +
  "// Re-run the script after any change to those; tests enforce this.\n" +
  "// (Excluded from Prettier via .prettierignore.)\n\n";

const body =
  banner +
  "export const OFFLINE_MODEL_EVALUATION = " +
  JSON.stringify(summary, null, 2) +
  " as const;\n";

writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
